// Bundles backend/handler.ts (+ story engine + zod) into one ESM file the
// Supabase Edge Function (Deno) can import. Run: npm run build:function
import { build } from 'esbuild';

await build({
  entryPoints: ['backend/handler.ts'],
  outfile: 'supabase/functions/generate-story/_bundle/handler.mjs',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  banner: { js: '// GENERATED by `npm run build:function` — do not edit. Source: backend/handler.ts + story-engine/' },
  legalComments: 'none',
  minify: true,
});
console.log('Built supabase/functions/generate-story/_bundle/handler.mjs');
